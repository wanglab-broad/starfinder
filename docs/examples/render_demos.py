"""Render the executed Get Started demos as Markdown pages with their figures under docs/get-started/.

Each notebook of ``DEMOS`` is converted with nbconvert's Markdown exporter as it is saved: the
saved outputs are kept and nothing is executed. Links to ``../../docs/<page>`` and between the
demos are rewritten for the page's place in the docs. Run from src/python after executing a
demo; ``--check`` writes nothing and exits 1 when a page or figure differs from a fresh
conversion:

    uv run python ../../docs/examples/render_demos.py [--check]
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NOTEBOOKS = ROOT / "example" / "introduction"
PAGES = ROOT / "docs" / "get-started"
# Notebook stem -> page stem; the pages fill the two demo slots of docs/get-started/index.md.
DEMOS = {"single_fov_demo": "single-fov-demo", "sample_demo": "multi-fov-demo"}


def render(stem: str) -> dict[str, bytes]:
    """The page and its figures for one demo, by path relative to docs/get-started/."""
    import nbformat
    from nbconvert import MarkdownExporter

    page = DEMOS[stem]
    notebook = nbformat.read(NOTEBOOKS / f"{stem}.ipynb", as_version=4)
    body, resources = MarkdownExporter().from_notebook_node(
        notebook, resources={"output_files_dir": f"{page}_files", "unique_key": page})
    body = body.replace("](../../docs/", "](../")
    for other, other_page in DEMOS.items():
        body = body.replace(f"]({other}.ipynb)", f"]({other_page}.md)")
    header = (f"% Generated by docs/examples/render_demos.py from example/introduction/{stem}.ipynb;"
              " edit the notebook, not this page.\n\n")
    files = {f"{page}.md": (header + body.strip() + "\n").encode()}
    files.update(resources.get("outputs", {}))
    return files


def written(stem: str) -> dict[str, bytes]:
    """The committed page and figures of one demo."""
    page = DEMOS[stem]
    files = {f"{page}.md": (PAGES / f"{page}.md").read_bytes()} if (PAGES / f"{page}.md").exists() else {}
    figures = PAGES / f"{page}_files"
    if figures.is_dir():
        files.update({p.relative_to(PAGES).as_posix(): p.read_bytes() for p in sorted(figures.iterdir())})
    return files


def main(check: bool) -> int:
    status = 0
    for stem, page in DEMOS.items():
        fresh = render(stem)
        if check:
            if fresh != written(stem):
                print(f"{page}: differs from a fresh conversion of {stem}.ipynb")
                status = 1
            continue
        figures = PAGES / f"{page}_files"
        if figures.is_dir():
            for path in figures.iterdir():
                path.unlink()
        for name, content in fresh.items():
            (PAGES / name).parent.mkdir(parents=True, exist_ok=True)
            (PAGES / name).write_bytes(content)
        print(f"{page}: {len(fresh) - 1} figures, {sum(map(len, fresh.values()))} bytes")
    return status


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="compare with the committed pages; write nothing")
    sys.exit(main(parser.parse_args().check))
