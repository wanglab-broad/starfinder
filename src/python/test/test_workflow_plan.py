# --- C2: the fingerprints ----------------------------------------------------------------------------------------

def _stats(manifest):
    stats = {}
    for item in manifest["inputs"]["files"].values():
        stats[item["path"] if os.path.isabs(item["path"]) else f"input:{item['path']}"] = item
    for rounds in manifest["inputs"]["images"].values():
        for labels in rounds.values():
            for item in labels.values():
                stats[f"input:{item['path']}"] = item
    return stats


def _fingerprints(manifest, code=None):
    """Each task's fingerprint from its components (design/specs/orchestration-engines.md, "The task fingerprint")."""
    stats, out = _stats(manifest), {}
    produced = {o for t in manifest["tasks"] for o in t["outputs"]}
    for task in manifest["tasks"]:
        entry = {k: v for k, v in task.items() if k not in ("fingerprint", "execution", "command")}
        inputs = [{k: stats[i][k] for k in ("path", "bytes", "mtime_ns")} for i in task["inputs"]
                  if i in stats and i not in produced]
        components = {"entry": entry, "blocks_sha256": task["blocks_sha256"], "inputs": inputs,
                      "needs": [out[n] for n in task["needs"]]}
        if code is not None:
            components["package"] = code
        out[task["id"]] = _sha(_canonical(components))
    return out


def _downstream(manifest, ids):
    """``ids`` and every task that needs one of them, transitively."""
    found = set(ids)
    for task in manifest["tasks"]:
        if set(task["needs"]) & found:
            found.add(task["id"])
    return found


def _changed(before, after):
    a = {t["id"]: t["fingerprint"] for t in before["tasks"]}
    b = {t["id"]: t["fingerprint"] for t in after["tasks"]}
    assert set(a) == set(b)
    return {k for k in a if a[k] != b[k]}


@pytest.mark.parametrize("code_version", ["keep", "rerun"])
def test_each_fingerprint_equals_an_independent_hash_of_its_components(work, code_version):
    config = dict(X.variants(work)["per-fov"], execution={"code_version": code_version})
    manifest = _plan(work, "per-fov", config)
    expected = _fingerprints(manifest, CODE if code_version == "rerun" else None)
    assert {t["id"]: t["fingerprint"] for t in manifest["tasks"]} == expected
    resolved = json.loads((X.output_root(work, "example-per-fov") / "workflow" / "resolved.json").read_text())
    c = resolved["configuration"]
    common = {k: v for k, v in c.items() if k not in ("processing", "morphology", "segmentation", "assignment",
                                                      "stitching", "assembly", "export", "report", "execution",
                                                      "root_input_path", "root_output_path", "api")}
    for task in manifest["tasks"]:
        part = {"common": common, "blocks": {b: c.get(b) for b in TASK_BLOCKS[task["kind"]]}}
        assert task["blocks_sha256"] == _sha(_canonical(part)), task["id"]


#: One key of each block of the per-fov variant, changed (each change passes the block's translator).
BLOCK_CHANGES = {
    "processing": lambda c: c["processing"]["spot_finding"].update(threshold_value=6.0),
    "morphology": lambda c: c["morphology"].update(rounds=["flamingo"], channel_images={"projection": "max"}),
    "segmentation": lambda c: c["segmentation"]["runs"][0].update(relabel=True),
    "assignment": lambda c: c["assignment"].update(correspondence={"match_fraction": 0.6}),
    "stitching": lambda c: c["stitching"]["config"].update(quality_threshold=-0.5),
    "assembly": lambda c: c["assembly"].update(duplicate_threshold=0.4),
    "export": lambda c: c["export"].update(fuse_labels=True),
    "report": lambda c: c["report"].update(positive_threshold=2),
}


@pytest.mark.parametrize("block", sorted(BLOCK_CHANGES))
def test_a_key_of_one_block_changes_the_fingerprints_of_its_kinds_and_their_downstream(work, block):
    config = X.variants(work)["per-fov"]
    before = _plan(work, "per-fov", config)
    changed = copy.deepcopy(config)
    BLOCK_CHANGES[block](changed)
    after = _plan(work, "per-fov", changed)
    readers = {t["id"] for t in after["tasks"] if block in TASK_BLOCKS[t["kind"]]}
    assert readers
    assert _changed(before, after) == _downstream(after, readers)


@pytest.mark.parametrize("replacement", ["another size", "an older modification time"])
def test_a_replaced_raw_image_changes_the_tasks_that_declare_it_and_their_downstream(work, replacement):
    config = X.variants(work)["per-fov"]
    before = _plan(work, "per-fov", config)
    image = X.input_root(work) / "round2" / "FOV_002" / "ch01.ome.tif"
    stat = image.stat()
    if replacement == "another size":
        image.write_bytes(image.read_bytes() + b"\0")
        os.utime(image, ns=(stat.st_atime_ns, stat.st_mtime_ns))
    else:
        image.write_bytes(image.read_bytes()[::-1])
        os.utime(image, ns=(stat.st_atime_ns, stat.st_mtime_ns - 86_400 * 10**9))
    after = _plan(work, "per-fov", config)
    declaring = {t["id"] for t in after["tasks"] if "input:round2/FOV_002/ch01.ome.tif" in t["inputs"]}
    assert declaring == {"summarize/sample/percentile_normalization/FOV_002", "fov/sample/FOV_002"}
    assert _changed(before, after) == _downstream(after, declaring)


def test_execution_and_the_roots_change_no_fingerprint_but_code_version_changes_every_one(work, tmp_path):
    config = X.variants(work)["molecules-only"]
