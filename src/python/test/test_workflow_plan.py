def test_without_the_report_block_no_report_task_is_planned(tmp_path, blocks):
    """From test_report_workflow.py, test_wf1_without_the_block_no_rule_and_no_output_is_added and
    test_wf1_with_the_block_the_report_rules_are_requested: without the report block the plan has no report or
    compare task and no output under report/; with it, exactly one report task per sample (in fovs.csv's order) and
    the compare task are added, and every other task is the same. (No workflow file includes the old report rules,
    and no MATLAB rule file names a report rule: test_workflow_boundary.py, C8.)"""
    config = W.dataset_keys(tmp_path, processing=copy.deepcopy(X.PROCESSING), **copy.deepcopy(blocks))
    W.write_inputs(config, "sample,fov_id\nsample1,tile_1\nsample2,tile_2\n")
    _, without = W.plan(tmp_path, "without", dict(config, output_id="without"))
    assert not [t for t in without["tasks"] if t["kind"] in ("report", "compare")]
    assert not [p for t in without["tasks"] for p in t["outputs"] if p.startswith("report/")]
    _, with_block = W.plan(tmp_path, "with", dict(config, output_id="with", report={}))
    added = [t for t in with_block["tasks"] if t["kind"] in ("report", "compare")]
    assert [t["id"] for t in added] == ["report/sample1", "report/sample2", "compare"]
    assert [o for t in added for o in t["outputs"]] == ["report/sample1/report.json", "report/sample2/report.json",
                                                         "report/index.html", "report/samples.csv"]
    assert [t["id"] for t in with_block["tasks"] if t not in added] == [t["id"] for t in without["tasks"]]


@pytest.mark.parametrize("template", ["{round}/{fov}", "{fov}/{round}"])
def test_the_plan_s_image_inputs_follow_the_template(tmp_path, template):
    """From test_workflow_input_layout.py, test_the_python_rule_inputs_follow_the_template: the fov task declares the
    channel files of every sequencing round, the morphology task those of its other round and the reference stain
    file of the reference round, each in the folder image_dir_template names; the plan reads the images where the
    template puts them."""
    config = W.dataset_keys(tmp_path, n_rounds=4, image_dir_template=template, processing=copy.deepcopy(X.PROCESSING),
                            reference_stains=[{"channel": "ch04", "name": "DAPI"}], morphology={},
                            additional_round=[{"round_name": "morph", "channel_order": [{"channel": "ch00",
                                                                                           "name": "DAPI"}]}])
    W.write_inputs(config, "sample,fov_id\ns1,F1\n")
    _, manifest = W.plan(tmp_path, "template", config)
    folder = lambda name: template.format(round=name, fov="F1")  # noqa: E731
    (fov,) = _of_kind(manifest, "fov")
    assert [i for i in fov["inputs"] if i.endswith(".tif")] == sorted(
        f"input:{folder(r)}/F1_{c}.tif" for r in ("round1", "round2", "round3", "round4")
        for c in ("ch00", "ch01", "ch02", "ch03"))
    (morphology,) = _of_kind(manifest, "morphology")
    assert f"input:{folder('morph')}/F1_ch00.tif" in morphology["inputs"]
    assert f"input:{folder('round1')}/F1_ch04.tif" in morphology["inputs"]


def test_the_plan_declares_the_configured_codebook(tmp_path):
    """From test_workflow_input_layout.py, test_the_rules_read_the_configured_codebook: the codebook is the file the
    key codebook names (relative to the input root), else <input_root>/genes.csv; the fov and assign tasks declare
    it, and no other codebook."""
    run = {"name": "cell", "target": "cell", "method": "import", "path": str(tmp_path / "{fov_id}.tif")}
    config = W.dataset_keys(tmp_path, codebook="panels/codebook.csv", processing=copy.deepcopy(X.PROCESSING),
                            segmentation={"runs": [run]}, assignment={"cells": "cell"})
    W.write_inputs(config, "sample,fov_id\ns1,F1\n", codebook=None)
    (W.input_root(config) / "panels").mkdir()
    (W.input_root(config) / "panels" / "codebook.csv").write_text("gene,barcode\n")
    (tmp_path / "F1.tif").write_bytes(b"")
    _, manifest = W.plan(tmp_path, "codebook", config)
    assert manifest["inputs"]["files"]["codebook"]["path"] == "panels/codebook.csv"
    for kind in ("fov", "assign"):
        (task,) = _of_kind(manifest, kind)
        assert [i for i in task["inputs"] if "codebook" in i or i.endswith("genes.csv")] == [
            "input:panels/codebook.csv"], kind
    default = dict(config, output_id="default")
    default.pop("codebook")
    (W.input_root(config) / "genes.csv").write_text("gene,barcode\n")
    _, manifest = W.plan(tmp_path, "default", default)
    assert manifest["inputs"]["files"]["codebook"]["path"] == "genes.csv"


def test_the_tasks_read_their_named_inputs_and_no_json_copy(tmp_path):
    """From test_workflow_python_inputs.py, test_the_python_rules_take_no_json_copy_and_the_matlab_rules_keep_it (its
    Python half): the fov task declares its rounds' image files and the codebook, the morphology task its rounds'
    image files and the reference stain file, each by path; no task declares a JSON copy of the configuration (the
    commands read the resolved configuration the manifest names, D2)."""
    config = W.dataset_keys(tmp_path, processing=copy.deepcopy(X.PROCESSING),
                            reference_stains=[{"channel": "ch04", "name": "DAPI"}], morphology={},
                            additional_round=[{"round_name": "morph", "channel_order": [{"channel": "ch00",
                                                                                           "name": "DAPI"}]}])
    W.write_inputs(config, "sample,fov_id\ns1,F1\n")
    _, manifest = W.plan(tmp_path, "named", config)
    (fov,) = _of_kind(manifest, "fov")
    assert fov["inputs"] == sorted([f"input:round{r}/F1/F1_ch0{c}.tif" for r in (1, 2, 3) for c in range(4)]
                                   + ["input:genes.csv"])
    (morphology,) = _of_kind(manifest, "morphology")
    assert morphology["inputs"] == ["input:morph/F1/F1_ch00.tif", "input:round1/F1/F1_ch04.tif"]
    assert not [i for t in manifest["tasks"] for i in t["inputs"] if i.endswith((".json", ".yaml"))]
    assert manifest["configuration"]["path"] == "workflow/resolved.json"


